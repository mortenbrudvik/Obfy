using System.Text;
using Microsoft.Extensions.Logging;
using Obfy.Core.Models;

namespace Obfy.Core.Services.Reporting;

/// <summary>
/// Generates HTML format obfuscation reports with visual styling.
/// </summary>
public class HtmlReportGenerator : IReportGenerator
{
    private readonly ILogger<HtmlReportGenerator> _logger;

    /// <summary>
    /// Creates a new HTML report generator.
    /// </summary>
    public HtmlReportGenerator(ILogger<HtmlReportGenerator> logger)
    {
        _logger = logger;
    }

    /// <inheritdoc/>
    public string FileExtension => ".html";

    /// <inheritdoc/>
    public async Task GenerateAsync(ObfuscationReport report, string outputPath, CancellationToken cancellationToken = default)
    {
        var html = await GenerateToStringAsync(report, cancellationToken);

        var directory = Path.GetDirectoryName(outputPath);
        if (!string.IsNullOrEmpty(directory))
        {
            Directory.CreateDirectory(directory);
        }

        await File.WriteAllTextAsync(outputPath, html, cancellationToken);
        _logger.LogInformation("HTML report written to {OutputPath}", outputPath);
    }

    /// <inheritdoc/>
    public Task<string> GenerateToStringAsync(ObfuscationReport report, CancellationToken cancellationToken = default)
    {
        var sb = new StringBuilder();

        sb.AppendLine("<!DOCTYPE html>");
        sb.AppendLine("<html lang=\"en\">");
        sb.AppendLine("<head>");
        sb.AppendLine("  <meta charset=\"UTF-8\">");
        sb.AppendLine("  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">");
        sb.AppendLine($"  <title>Obfuscation Report - {Path.GetFileName(report.FileInfo.InputPath)}</title>");
        sb.AppendLine(GetStyles());
        sb.AppendLine("</head>");
        sb.AppendLine("<body>");

        // Header
        sb.AppendLine("  <header>");
        sb.AppendLine("    <h1>Obfuscation Report</h1>");
        sb.AppendLine($"    <p class=\"subtitle\">Generated by Obfy v{report.Metadata.ObfyVersion}</p>");
        sb.AppendLine("  </header>");

        sb.AppendLine("  <main>");

        // Summary section
        GenerateSummarySection(sb, report);

        // File info section
        GenerateFileInfoSection(sb, report);

        // Statistics section
        GenerateStatisticsSection(sb, report);

        // Symbol summary section
        GenerateSymbolSummarySection(sb, report);

        // Settings section
        GenerateSettingsSection(sb, report);

        // Processing times section
        GenerateProcessingTimesSection(sb, report);

        // Warnings section
        GenerateWarningsSection(sb, report);

        sb.AppendLine("  </main>");

        // Footer
        sb.AppendLine("  <footer>");
        sb.AppendLine($"    <p>Report generated at {report.Metadata.GeneratedAt:yyyy-MM-dd HH:mm:ss} UTC</p>");
        sb.AppendLine("  </footer>");

        sb.AppendLine("</body>");
        sb.AppendLine("</html>");

        return Task.FromResult(sb.ToString());
    }

