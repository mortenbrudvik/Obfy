    private static void GenerateSummarySection(StringBuilder sb, ObfuscationReport report)
    {
        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>Summary</h2>");
        sb.AppendLine("      <table>");
        sb.AppendLine($"        <tr><td>Input File</td><td>{Path.GetFileName(report.FileInfo.InputPath)}</td></tr>");
        sb.AppendLine($"        <tr><td>Obfuscation Level</td><td>{report.Metadata.Level}</td></tr>");
        sb.AppendLine($"        <tr><td>Total Duration</td><td>{report.Metadata.TotalElapsedTime:mm\\:ss\\.fff}</td></tr>");
        sb.AppendLine($"        <tr><td>Total Transformations</td><td><strong>{report.Statistics.TotalTransformations:N0}</strong></td></tr>");
        sb.AppendLine("      </table>");
        sb.AppendLine("    </div>");
    }

    private static void GenerateFileInfoSection(StringBuilder sb, ObfuscationReport report)
    {
        var sizeChangeClass = report.FileInfo.SizeDifferenceBytes switch
        {
            > 0 => "positive",
            < 0 => "negative",
            _ => "neutral"
        };

        var sizeChangeSign = report.FileInfo.SizeDifferenceBytes >= 0 ? "+" : "";

        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>File Information</h2>");
        sb.AppendLine("      <table>");
        sb.AppendLine($"        <tr><td>Input Path</td><td>{report.FileInfo.InputPath}</td></tr>");
        sb.AppendLine($"        <tr><td>Output Path</td><td>{report.FileInfo.OutputPath}</td></tr>");
        sb.AppendLine($"        <tr><td>Input Size</td><td>{FormatBytes(report.FileInfo.InputSizeBytes)}</td></tr>");
        sb.AppendLine($"        <tr><td>Output Size</td><td>{FormatBytes(report.FileInfo.OutputSizeBytes)}</td></tr>");
        sb.AppendLine($"        <tr><td>Size Change</td><td><span class=\"size-change {sizeChangeClass}\">{sizeChangeSign}{FormatBytes(report.FileInfo.SizeDifferenceBytes)} ({sizeChangeSign}{report.FileInfo.SizeChangePercent:F1}%)</span></td></tr>");
        sb.AppendLine("      </table>");
        sb.AppendLine("    </div>");
    }

    private static void GenerateStatisticsSection(StringBuilder sb, ObfuscationReport report)
    {
        var stats = report.Statistics;

        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>Transformation Statistics</h2>");
        sb.AppendLine("      <div class=\"stats-grid\">");

        AddStatItem(sb, stats.StringsEncrypted, "Strings Encrypted");
        AddStatItem(sb, stats.ConstantsEncrypted, "Constants Encrypted");
        AddStatItem(sb, stats.ResourcesEncrypted, "Resources Encrypted");
        AddStatItem(sb, stats.TypesRenamed, "Types Renamed");
        AddStatItem(sb, stats.MethodsRenamed, "Methods Renamed");
        AddStatItem(sb, stats.FieldsRenamed, "Fields Renamed");
        AddStatItem(sb, stats.PropertiesRenamed, "Properties Renamed");
        AddStatItem(sb, stats.ParametersRenamed, "Parameters Renamed");
        AddStatItem(sb, stats.MethodsControlFlowObfuscated, "Control Flow");
        AddStatItem(sb, stats.ProtectionsApplied, "Protections");
        AddStatItem(sb, stats.MetadataItemsRemoved, "Metadata Removed");
        AddStatItem(sb, stats.TotalTransformations, "Total", highlight: true);

        sb.AppendLine("      </div>");
        sb.AppendLine("    </div>");
    }

    private static void AddStatItem(StringBuilder sb, int value, string label, bool highlight = false)
    {
        var valueClass = highlight ? "stat-value highlight" : "stat-value";
        sb.AppendLine($"        <div class=\"stat-item\"><div class=\"{valueClass}\">{value:N0}</div><div class=\"stat-label\">{label}</div></div>");
    }

    private static void GenerateSymbolSummarySection(StringBuilder sb, ObfuscationReport report)
    {
        var summary = report.SymbolSummary;

        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>Symbol Renaming Summary</h2>");
        sb.AppendLine("      <table>");
        sb.AppendLine($"        <tr><td>Naming Mode</td><td>{summary.NamingModeUsed}</td></tr>");
        sb.AppendLine($"        <tr><td>Total Symbols Renamed</td><td>{summary.TotalSymbolsRenamed:N0}</td></tr>");
        sb.AppendLine($"        <tr><td>Types</td><td>{summary.TypesRenamed:N0}</td></tr>");
        sb.AppendLine($"        <tr><td>Methods</td><td>{summary.MethodsRenamed:N0}</td></tr>");
        sb.AppendLine($"        <tr><td>Fields</td><td>{summary.FieldsRenamed:N0}</td></tr>");
        sb.AppendLine($"        <tr><td>Properties</td><td>{summary.PropertiesRenamed:N0}</td></tr>");
        sb.AppendLine($"        <tr><td>Parameters</td><td>{summary.ParametersRenamed:N0}</td></tr>");
        sb.AppendLine("      </table>");
        sb.AppendLine("    </div>");
    }

    private static void GenerateSettingsSection(StringBuilder sb, ObfuscationReport report)
    {
        var settings = report.SettingsUsed;

        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>Settings Used</h2>");
        sb.AppendLine("      <table>");

        AddSettingRow(sb, "String Encryption", settings.StringEncryptionEnabled);
        AddSettingRow(sb, "Constant Encryption", settings.ConstantEncryptionEnabled);
        AddSettingRow(sb, "Resource Encryption", settings.ResourceEncryptionEnabled);
        AddSettingRow(sb, "Control Flow Obfuscation", settings.ControlFlowEnabled);
        AddSettingRow(sb, "Symbol Renaming", settings.SymbolRenamingEnabled);
        AddSettingRow(sb, "Anti-Debug Protection", settings.AntiDebugEnabled);
        AddSettingRow(sb, "Metadata Removal", settings.MetadataRemovalEnabled);
        AddSettingRow(sb, "Preserve Public API", settings.PreservePublicApi);

        sb.AppendLine("      </table>");
        sb.AppendLine("    </div>");
    }

    private static void AddSettingRow(StringBuilder sb, string name, bool enabled)
    {
        var badgeClass = enabled ? "badge enabled" : "badge disabled";
        var badgeText = enabled ? "Enabled" : "Disabled";
        sb.AppendLine($"        <tr><td>{name}</td><td><span class=\"{badgeClass}\">{badgeText}</span></td></tr>");
    }

    private static void GenerateProcessingTimesSection(StringBuilder sb, ObfuscationReport report)
    {
        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>Processing Times</h2>");

        if (report.ProcessingTimes.Count == 0)
        {
            sb.AppendLine("      <p class=\"no-data\">No timing data available.</p>");
        }
        else
        {
            sb.AppendLine("      <table>");
            sb.AppendLine("        <tr><th>Obfuscator</th><th>Duration</th><th>Transformations</th></tr>");

            foreach (var entry in report.ProcessingTimes)
            {
                sb.AppendLine($"        <tr><td>{entry.ObfuscatorName}</td><td>{entry.Duration.TotalMilliseconds:F0}ms</td><td>{entry.TransformationsApplied:N0}</td></tr>");
            }

            sb.AppendLine("      </table>");
        }

        sb.AppendLine("    </div>");
    }

    private static void GenerateWarningsSection(StringBuilder sb, ObfuscationReport report)
    {
        sb.AppendLine("    <div class=\"card\">");
        sb.AppendLine("      <h2>Warnings</h2>");

        if (report.Warnings.Count == 0)
        {
            sb.AppendLine("      <p class=\"no-data\">No warnings generated.</p>");
        }
        else
        {
            foreach (var warning in report.Warnings)
            {
                var severityClass = warning.Severity.ToString().ToLowerInvariant();
                sb.AppendLine($"      <div class=\"warning-item {severityClass}\">");
                sb.AppendLine($"        <div class=\"category\">{warning.Category}</div>");
                sb.AppendLine($"        <div>{warning.Message}</div>");
                if (!string.IsNullOrEmpty(warning.Details))
                {
                    sb.AppendLine($"        <div style=\"margin-top:5px;font-size:0.9em;opacity:0.8;\">{warning.Details}</div>");
                }
                sb.AppendLine("      </div>");
            }
        }

        sb.AppendLine("    </div>");
    }

    private static string FormatBytes(long bytes)
    {
        var absBytes = Math.Abs(bytes);
        string[] suffixes = { "B", "KB", "MB", "GB" };
        var suffixIndex = 0;
        var size = (double)absBytes;

        while (size >= 1024 && suffixIndex < suffixes.Length - 1)
        {
            size /= 1024;
            suffixIndex++;
        }

        var formatted = size < 10 ? $"{size:F2}" : size < 100 ? $"{size:F1}" : $"{size:F0}";
        return $"{(bytes < 0 ? "-" : "")}{formatted} {suffixes[suffixIndex]}";
    }
}
